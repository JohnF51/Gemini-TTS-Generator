import re

with open(r"j:\Vlastne_aplikacie\Gemini_TTS\Gemini_TTS_v7.py", "r", encoding="utf-8") as f:
    content = f.read()

# Replace self.tr("...") with "..."
for sk, en in en_translations.items():
    escaped_sk = re.escape(sk)
    # the strings in the file could be inside f-strings, double quotes, or single quotes
    pattern1 = r'self\.tr\("' + escaped_sk + r'"\)'
    pattern2 = r"self\.tr\('" + escaped_sk + r"'\)"
    
    content = re.sub(pattern1, f'"{en}"', content)
    content = re.sub(pattern2, f"'{en}'", content)

remaining = re.findall(r'self\.tr\([^)]*\)', content)
for r in remaining:
    print("Warning: remained:", r)

with open(r"j:\Vlastne_aplikacie\Gemini_TTS\Gemini_TTS_v7.py", "w", encoding="utf-8") as f:
    f.write(content)

print("Done replacing.")
